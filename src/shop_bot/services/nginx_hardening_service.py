HARDENING_CONF_PATH = CONF_D_DIR / "security_hardening.conf"
SYSCTL_CONF_PATH = Path("/etc/sysctl.d/99-neovpn-security.conf")

# Log paths (standard Linux locations)
DEFAULT_ACCESS_LOG = Path("/var/log/nginx/access.log")
DEFAULT_ERROR_LOG = Path("/var/log/nginx/error.log")

# Audit cache / state
STATUS_FILE_PATH = DATA_DIR / "nginx_hardening_status.json"
TRIGGER_NGINX_PATH = DATA_DIR / "run_nginx_harden.trigger"
TRIGGER_SYSCTL_PATH = DATA_DIR / "run_sysctl_harden.trigger"


class NginxHardeningService:
    """Service for auditing, configuring, and verifying Nginx Overflow Shield

    and Linux kernel network stack hardening (sysctl somaxconn, syn-cookies).
    Includes Fail-Safe Engine with automatic rollback on validation error.
    """

    # Target directives to verify and enforce
    EXPECTED_DIRECTIVES = {
        "server_tokens": "off",
        "client_header_buffer_size": "1k",
        "large_client_header_buffers": "4 8k",
        "client_body_buffer_size": "16k",
        "client_max_body_size": "10m",
        "client_header_timeout": "10s",
        "client_body_timeout": "10s",
        "send_timeout": "10s",
        "keepalive_timeout": "30s",
        "reset_timedout_connection": "on",
        "limit_conn_zone": "zone=addr_limit:10m",
        "limit_req_zone": "zone=req_limit:10m",
    }

    # Sysctl kernel parameters for TCP stack hardening
    EXPECTED_SYSCTL = {
        "net.ipv4.tcp_syncookies": "1",
        "net.core.somaxconn": "4096",
        "net.ipv4.tcp_max_syn_backlog": "4096",
        "net.ipv4.tcp_fin_timeout": "15",
    }

    @classmethod
    def get_nginx_version(cls) -> Optional[str]:
        """Detect installed Nginx version via `nginx -v`."""
        nginx_bin = shutil.which("nginx") or "/usr/sbin/nginx"
        if not os.path.exists(nginx_bin) and shutil.which("nginx") is None:
            if os.name == "nt":
                return "nginx/1.24.0 (Dev Emulation)"
            return None

        try:
            # nginx -v writes version info to stderr
            proc = subprocess.run(
                [nginx_bin, "-v"],
                capture_output=True,
                text=True,
                timeout=5,
            )
            raw = (proc.stderr or "") + (proc.stdout or "")
            match = re.search(r"nginx version:\s*(.+)", raw, re.IGNORECASE)
            if match:
                return match.group(1).strip()
            return raw.strip() or "nginx/unknown"
        except Exception as e:
            logger.warning(f"Error checking Nginx version: {e}")
            return None

    @classmethod
    def get_static_conf_path(cls) -> Optional[Path]:
        """Return path to physical static configuration file if present in repository."""
        candidates = [
            PROJECT_ROOT / "deploy" / "nginx" / "security_hardening.conf",
            PROJECT_ROOT / "src" / "shop_bot" / "config" / "security_hardening.conf",
        ]
        for p in candidates:
            if p.exists():
                return p
        return None

    @classmethod
    def generate_hardening_conf_content(cls) -> str:
        """Generate content for /etc/nginx/conf.d/security_hardening.conf.

        First attempts to load from the repository static file; falls back to embedded standard.
        """
        static_path = cls.get_static_conf_path()
        if static_path:
            try:
                return static_path.read_text(encoding="utf-8")
            except Exception as e:
                logger.warning(f"Error reading static config {static_path}: {e}")

        return """# ==============================================================================
# 3X-UI ShopBot — Nginx Overflow Shield & Security Hardening
# Auto-generated by NginxHardeningService
# ==============================================================================

# 1. Hide Server Signature (Prevents banner grabbing)
server_tokens off;

# 2. Buffer Overflow & Integer Overflow Shield
client_header_buffer_size 1k;
large_client_header_buffers 4 8k;
client_body_buffer_size 16k;
client_max_body_size 10m;

# 3. Slowloris & Resource Exhaustion Defense Timeouts
client_header_timeout 10s;
client_body_timeout 10s;
send_timeout 10s;
keepalive_timeout 30s;
reset_timedout_connection on;

# 4. Payment Gateway Webhook Whitelist Exemption
# Payment callback notifications must never be blocked by rate limiting.
# In Nginx, an empty string key in limit_req_zone bypasses rate-limiting entirely.
map $request_uri $limit_req_exempt_key {
    default $binary_remote_addr;
    ~^/webhook/ "";
    ~^/.*webhook.* "";
    ~^/payok-webhook "";
    ~^/lavatop-webhook "";
    ~^/cryptomus-webhook "";
    ~^/yookassa-webhook "";
    ~^/aaio-webhook "";
    ~^/platega-webhook "";
}

# 5. Rate Limiting and Connection Concurrency Zones
limit_conn_zone $binary_remote_addr zone=addr_limit:10m;
limit_req_zone $limit_req_exempt_key zone=req_limit:10m rate=15r/s;

# 6. Default Protection Applied Across Virtual Hosts
limit_conn addr_limit 20;
limit_req zone=req_limit burst=30 nodelay;
"""

    @classmethod
    def audit_nginx_configuration(cls) -> Dict[str, Any]:
        """Analyze current Nginx configuration for security hardening directives."""
        DATA_DIR.mkdir(parents=True, exist_ok=True)
        nginx_version = cls.get_nginx_version()

        # If on Windows without Nginx, check status file or provide dev baseline
        if os.name == "nt" and (not shutil.which("nginx")):
            cached = cls._load_cached_status()
            if cached and "nginx" in cached:
                return cached["nginx"]
            return cls._get_dev_nginx_audit(nginx_version or "nginx/1.24.0 (Windows Dev)")

        # On Linux: attempt to run `nginx -T` to get the active parsed configuration
        active_config = ""
        config_test_ok = False
        nginx_bin = shutil.which("nginx") or "/usr/sbin/nginx"

        if os.path.exists(nginx_bin) or shutil.which("nginx"):
            try:
                sudo_prefix = ["sudo"] if os.geteuid() != 0 and shutil.which("sudo") else []
                proc = subprocess.run(
                    sudo_prefix + [nginx_bin, "-T"],
                    capture_output=True,
                    text=True,
                    timeout=10,
                )
                active_config = proc.stdout or ""
                config_test_ok = proc.returncode == 0
            except Exception as e:
                logger.warning(f"Error running nginx -T: {e}")

        # Fallback if nginx -T didn't work: read /etc/nginx/nginx.conf & conf.d/*.conf
        if not active_config:
            if HARDENING_CONF_PATH.exists():
                try:
                    active_config += HARDENING_CONF_PATH.read_text(encoding="utf-8", errors="ignore")
                except Exception:
                    pass
            if NGINX_CONF_PATH.exists():
                try:
                    active_config += "\n" + NGINX_CONF_PATH.read_text(encoding="utf-8", errors="ignore")
                except Exception:
                    pass

        # Inspect directives against expected settings
        directives_audit: Dict[str, Dict[str, Any]] = {}
        missing_directives: List[str] = []

        for directive, expected_val in cls.EXPECTED_DIRECTIVES.items():
            pattern = rf"^\s*{re.escape(directive)}\s+([^;]+);"
            matches = re.findall(pattern, active_config, re.MULTILINE)
            if matches:
                current_val = matches[-1].strip()
                # Check whether current value matches or satisfies requirement
                ok = expected_val in current_val or current_val == expected_val
                directives_audit[directive] = {
                    "current": current_val,
                    "expected": expected_val,
                    "ok": ok,
                }
                if not ok:
                    missing_directives.append(directive)
            else:
                directives_audit[directive] = {
                    "current": None,
                    "expected": expected_val,
                    "ok": False,
                }
                missing_directives.append(directive)

        is_hardened = (len(missing_directives) == 0) and (HARDENING_CONF_PATH.exists() or len(active_config) > 500)
        status = "SECURE" if is_hardened else ("WARNING" if directives_audit.get("server_tokens", {}).get("ok") else "NOT_CONFIGURED")

        return {
            "version": nginx_version or "Nginx not found",
            "installed": bool(nginx_version),
            "hardened": is_hardened,
            "status": status,
            "hardening_file_exists": HARDENING_CONF_PATH.exists(),
            "config_test_ok": config_test_ok,
            "directives": directives_audit,
            "missing_directives": missing_directives,
            "checked_at": datetime.utcnow().strftime("%Y-%m-%dT%H:%M:%SZ"),
        }

    @classmethod
    def audit_sysctl(cls) -> Dict[str, Any]:
        """Audit sysctl parameters (SYN-cookies, somaxconn, syn_backlog, fin_timeout)."""
        sysctl_results: Dict[str, Dict[str, Any]] = {}
        missing_params: List[str] = []

        # Windows Dev environment
        if os.name == "nt":
            cached = cls._load_cached_status()
            if cached and "sysctl" in cached:
                return cached["sysctl"]
            for param, expected in cls.EXPECTED_SYSCTL.items():
                sysctl_results[param] = {
                    "current": expected,
                    "expected": expected,
                    "ok": True,
                }
            return {
                "status": "SECURE",
                "all_applied": True,
                "params": sysctl_results,
                "missing_params": [],
            }

        # Linux: check /proc/sys values directly
        proc_map = {
            "net.ipv4.tcp_syncookies": Path("/proc/sys/net/ipv4/tcp_syncookies"),
            "net.core.somaxconn": Path("/proc/sys/net/core/somaxconn"),
            "net.ipv4.tcp_max_syn_backlog": Path("/proc/sys/net/ipv4/tcp_max_syn_backlog"),
            "net.ipv4.tcp_fin_timeout": Path("/proc/sys/net/ipv4/tcp_fin_timeout"),
        }

        all_ok = True
        for param, expected_val in cls.EXPECTED_SYSCTL.items():
            curr_val = None
            proc_file = proc_map.get(param)
            if proc_file and proc_file.exists():
                try:
                    curr_val = proc_file.read_text().strip()
                except Exception:
                    pass

            # Fallback to sysctl -n
            if curr_val is None and shutil.which("sysctl"):
                try:
                    res = subprocess.run(["sysctl", "-n", param], capture_output=True, text=True, timeout=2)
                    if res.returncode == 0:
                        curr_val = res.stdout.strip()
                except Exception:
                    pass

            is_ok = (curr_val == expected_val) or (curr_val and int(curr_val) >= int(expected_val) if curr_val.isdigit() and expected_val.isdigit() and param != "net.ipv4.tcp_fin_timeout" else curr_val == expected_val)
            if not is_ok:
                all_ok = False
                missing_params.append(param)

            sysctl_results[param] = {
                "current": curr_val or "unknown",
                "expected": expected_val,
                "ok": is_ok,
            }

        return {
            "status": "SECURE" if all_ok else "WARNING",
            "all_applied": all_ok,
            "params": sysctl_results,
            "missing_params": missing_params,
        }

    @classmethod
    def apply_sysctl_hardening(cls) -> Tuple[bool, str, Dict[str, Any]]:
        """Apply recommended sysctl network parameters to host kernel."""
        DATA_DIR.mkdir(parents=True, exist_ok=True)

        # Docker environment handling: create trigger file for host
        if os.path.exists("/.dockerenv"):
            logger.info("Docker environment detected. Creating sysctl trigger file...")
            try:
                with open(TRIGGER_SYSCTL_PATH, "w", encoding="utf-8") as f:
                    json.dump(
                        {
                            "action": "apply_sysctl_hardening",
                            "requested_at": datetime.utcnow().strftime("%Y-%m-%dT%H:%M:%SZ"),
                            "params": cls.EXPECTED_SYSCTL,
                        },
                        f,
                        indent=2,
                    )
            except Exception as e:
                return False, f"Ошибка создания триггера {TRIGGER_SYSCTL_PATH}: {e}", cls.audit_sysctl()

            # Poll for update
            time.sleep(1.0)
            return True, "[Docker Host] Триггер применения параметров sysctl успешно отправлен хост-серверу.", cls.audit_sysctl()

        # Windows Dev environment
        if os.name == "nt":
            status = cls.audit_sysctl()
            cls._save_cached_status({"sysctl": status})
            return True, "[Windows Dev] Сетевые параметры ядра (sysctl) успешно эмулированы и применены.", status

        # Linux Host execution
        sudo_prefix = ["sudo"] if os.geteuid() != 0 and shutil.which("sudo") else []
        output_lines = []

        try:
            # 1. Update /etc/sysctl.d/99-neovpn-security.conf
            sysctl_content = ""
            if SYSCTL_CONF_PATH.exists():
                sysctl_content = SYSCTL_CONF_PATH.read_text(encoding="utf-8", errors="ignore")

            lines_to_add = []
            for param, val in cls.EXPECTED_SYSCTL.items():
                pattern = rf"^\s*{re.escape(param)}\s*="
                if not re.search(pattern, sysctl_content, re.MULTILINE):
                    lines_to_add.append(f"{param} = {val}\n")

            if lines_to_add:
                tmp_file = DATA_DIR / "sysctl_append.tmp"
                tmp_file.write_text(sysctl_content + "\n" + "".join(lines_to_add), encoding="utf-8")
                subprocess.run(sudo_prefix + ["cp", str(tmp_file), str(SYSCTL_CONF_PATH)], check=True)
                subprocess.run(sudo_prefix + ["chmod", "644", str(SYSCTL_CONF_PATH)], check=True)
                tmp_file.unlink(missing_ok=True)

            # 2. Apply via sysctl -w or sysctl -p
            for param, val in cls.EXPECTED_SYSCTL.items():
                cmd = sudo_prefix + ["sysctl", "-w", f"{param}={val}"]
                res = subprocess.run(cmd, capture_output=True, text=True)
                if res.returncode == 0:
                    output_lines.append(f"✓ {param} = {val}")
                else:
                    output_lines.append(f"⚠️ {param}: {res.stderr.strip()}")

            if SYSCTL_CONF_PATH.exists():
                subprocess.run(sudo_prefix + ["sysctl", "-p", str(SYSCTL_CONF_PATH)], capture_output=True)

            audit_res = cls.audit_sysctl()
            return True, "\n".join(output_lines) or "Параметры sysctl успешно применены.", audit_res

        except Exception as e:
            err_msg = f"Исключение при применении sysctl: {e}"
            logger.error(err_msg)
            return False, err_msg, cls.audit_sysctl()

    @classmethod
    def apply_nginx_hardening(cls) -> Tuple[bool, str, Dict[str, Any]]:
        """Apply Nginx hardening directives with Fail-Safe Engine (atomic update & rollback).

        Returns: (success: bool, message: str, audit_data: dict)
        """
        DATA_DIR.mkdir(parents=True, exist_ok=True)
        timestamp = datetime.utcnow().strftime("%Y%m%d_%H%M%S")

        # Docker environment handling: create trigger file for host if not directly manageable
        if os.path.exists("/.dockerenv") and not NGINX_CONF_PATH.exists():
            logger.info("Docker environment detected without host /etc/nginx mount. Writing trigger...")
            try:
                with open(TRIGGER_NGINX_PATH, "w", encoding="utf-8") as f:
                    json.dump(
                        {
                            "action": "apply_nginx_hardening",
                            "requested_at": datetime.utcnow().strftime("%Y-%m-%dT%H:%M:%SZ"),
                        },
                        f,
                        indent=2,
                    )
                time.sleep(1.0)
                audit_res = cls.audit_nginx_configuration()
                return True, "[Docker Host] Триггер харденинга Nginx успешно создан для хост-демона.", audit_res
            except Exception as e:
                return False, f"Ошибка создания триггера харденинга: {e}", cls.audit_nginx_configuration()

        # Windows Dev environment
        if os.name == "nt":
            mock_conf = DATA_DIR / "security_hardening.conf"
            mock_conf.write_text(cls.generate_hardening_conf_content(), encoding="utf-8")
            dev_audit = cls._get_dev_nginx_audit("nginx/1.24.0 (Windows Dev Hardened)")
            dev_audit["hardened"] = True
            dev_audit["status"] = "SECURE"
            dev_audit["hardening_file_exists"] = True
            dev_audit["config_test_ok"] = True
            for k in dev_audit["directives"]:
                dev_audit["directives"][k]["ok"] = True
            dev_audit["missing_directives"] = []
            cls._save_cached_status({"nginx": dev_audit})
            return (
                True,
                "[Windows Dev] Конфигурация Nginx Overflow Shield успешно сгенерирована (data/security_hardening.conf).\n"
                "Синтаксис директив проверен: OK.\n"
                "Мягкая перезагрузка Nginx (nginx -s reload) эмулирована.",
                dev_audit,
            )

        # Linux Host Fail-Safe Application
        sudo_prefix = ["sudo"] if os.geteuid() != 0 and shutil.which("sudo") else []
        nginx_bin = shutil.which("nginx") or "/usr/sbin/nginx"

        if not os.path.exists(nginx_bin) and shutil.which("nginx") is None:
            return False, "Nginx не установлен на сервере.", cls.audit_nginx_configuration()

        backup_created = False
        backup_path = CONF_D_DIR / f"security_hardening.conf.bak_{timestamp}"
        had_previous_conf = HARDENING_CONF_PATH.exists()
        previous_content = ""

        try:
            # 1. Step: Ensure conf.d directory exists
            subprocess.run(sudo_prefix + ["mkdir", "-p", str(CONF_D_DIR)], check=True)

            # 2. Step: Create backup if file exists
            if had_previous_conf:
                previous_content = HARDENING_CONF_PATH.read_text(encoding="utf-8", errors="ignore")
                subprocess.run(sudo_prefix + ["cp", str(HARDENING_CONF_PATH), str(backup_path)], check=True)
                backup_created = True
                logger.info(f"Nginx hardening backup created at {backup_path}")

            # 3. Step: Write new configuration to temp file
            tmp_conf = DATA_DIR / f"security_hardening_{timestamp}.tmp"
            tmp_conf.write_text(cls.generate_hardening_conf_content(), encoding="utf-8")

            # 4. Step: Move temp file to destination
            subprocess.run(sudo_prefix + ["cp", str(tmp_conf), str(HARDENING_CONF_PATH)], check=True)
            subprocess.run(sudo_prefix + ["chmod", "644", str(HARDENING_CONF_PATH)], check=True)
            tmp_conf.unlink(missing_ok=True)

            # 5. Step: Validate configuration with `nginx -t`
            test_proc = subprocess.run(
                sudo_prefix + [nginx_bin, "-t"],
                capture_output=True,
                text=True,
                timeout=10,
            )
            test_output = (test_proc.stdout or "") + ("\n" + test_proc.stderr if test_proc.stderr else "")

            # 6. Step: Check validation result
            if test_proc.returncode == 0:
                # Validation SUCCESS: Soft reload Nginx
                reload_proc = subprocess.run(
                    sudo_prefix + [nginx_bin, "-s", "reload"],
                    capture_output=True,
                    text=True,
                    timeout=10,
                )
                reload_output = (reload_proc.stdout or "") + ("\n" + reload_proc.stderr if reload_proc.stderr else "")
                logger.info(f"Nginx reload successful: {reload_output.strip()}")

                audit_res = cls.audit_nginx_configuration()
                success_msg = (
                    "✔ Конфигурация Nginx Overflow Shield успешно применена.\n"
                    f"Тест синтаксиса (nginx -t): OK.\n"
                    f"Служба перезагружена без разрыва соединений (nginx -s reload).\n"
                    f"Вывод теста:\n{test_output.strip()}"
                )
                return True, success_msg, audit_res
            else:
                # Validation FAILED: Automatic Rollback!
                logger.error(f"nginx -t validation failed! Code: {test_proc.returncode}. Output: {test_output}")
                cls._perform_rollback(sudo_prefix, had_previous_conf, backup_path, HARDENING_CONF_PATH)

                # Re-check syntax after rollback
                rollback_check = subprocess.run(sudo_prefix + [nginx_bin, "-t"], capture_output=True, text=True)
                rollback_msg = "Откат к предыдущей конфигурации выполнен успешно." if rollback_check.returncode == 0 else "ВНИМАНИЕ: Проверьте синтаксис Nginx вручную."

                err_msg = (
                    "❌ Ошибка проверки конфигурации Nginx (nginx -t)!\n"
                    "Сработал защитный механизм (Fail-Safe Rollback).\n"
                    f"{rollback_msg}\n\n"
                    f"Лог ошибки проверки:\n{test_output.strip()}"
                )
                return False, err_msg, cls.audit_nginx_configuration()

        except Exception as e:
            logger.error(f"Exception during Nginx hardening: {e}")
            cls._perform_rollback(sudo_prefix, had_previous_conf, backup_path, HARDENING_CONF_PATH)
            return False, f"Исключение при обновлении Nginx: {e}. Выполнен откат к бэкапу.", cls.audit_nginx_configuration()

    @classmethod
    def _perform_rollback(cls, sudo_prefix: List[str], had_previous: bool, backup_path: Path, target_path: Path) -> None:
        """Helper to rollback configuration changes."""
        try:
            if had_previous and backup_path.exists():
                subprocess.run(sudo_prefix + ["cp", str(backup_path), str(target_path)], check=True)
                logger.info(f"Restored backup from {backup_path} to {target_path}")
            else:
                # Remove newly created file
                subprocess.run(sudo_prefix + ["rm", "-f", str(target_path)], check=True)
                logger.info(f"Removed invalid file {target_path}")
        except Exception as re:
            logger.error(f"Error during rollback: {re}")

    @classmethod
    def parse_nginx_logs(cls, hours: int = 24, max_lines: int = 10000) -> Dict[str, Any]:
        """Parse Nginx access.log and error.log for buffer/request size attack codes (414, 400, 413, 494)

        and abnormal worker crashes within the specified time window.
        """
        anomalies = {
            "total": 0,
            "code_414": 0,  # URI Too Long (Buffer overflow attempt)
            "code_400": 0,  # Bad Request (Malformed header/syntax attack)
            "code_413": 0,  # Payload Too Large
            "code_494": 0,  # Request Header Too Large
            "worker_crashes": 0,
            "recent_events": [],
            "scanned_period_hours": hours,
            "checked_at": datetime.utcnow().strftime("%Y-%m-%dT%H:%M:%SZ"),
        }

        # Dev / Windows mock or log files search
        access_log_paths = [
            DEFAULT_ACCESS_LOG,
            Path("/var/log/nginx/access.log.1"),
            DATA_DIR / "nginx_access.log",
        ]
        error_log_paths = [
            DEFAULT_ERROR_LOG,
            Path("/var/log/nginx/error.log.1"),
            DATA_DIR / "nginx_error.log",
        ]

        found_access_logs = [p for p in access_log_paths if p.exists()]
        found_error_logs = [p for p in error_log_paths if p.exists()]

        if not found_access_logs and not found_error_logs:
            # Return baseline clean stats
            return anomalies

        cutoff_time = datetime.utcnow() - timedelta(hours=hours)

        # 1. Parse Access Logs
        # Standard format: IP - User [28/Oct/2026:14:00:00 +0000] "GET / HTTP/1.1" 414 ...
        status_regex = re.compile(
            r'\[(?P<time>[^\]]+)\]\s+"(?P<req>[^"]*)"\s+(?P<status>400|413|414|494)\s+(?P<bytes>\d+)'
        )

        for log_path in found_access_logs:
            try:
                lines = cls._tail_file(log_path, max_lines)
                for line in lines:
                    m = status_regex.search(line)
                    if m:
                        status_code = m.group("status")
                        raw_time = m.group("time")
                        log_dt = cls._parse_nginx_timestamp(raw_time)

                        # Filter by time if parseable
                        if log_dt and log_dt < cutoff_time:
                            continue

                        anomalies["total"] += 1
                        if status_code == "414":
                            anomalies["code_414"] += 1
                        elif status_code == "400":
                            anomalies["code_400"] += 1
                        elif status_code == "413":
                            anomalies["code_413"] += 1
                        elif status_code == "494":
                            anomalies["code_494"] += 1

                        if len(anomalies["recent_events"]) < 20:
                            anomalies["recent_events"].append(
                                {
                                    "type": f"HTTP {status_code}",
                                    "timestamp": raw_time,
                                    "request": m.group("req")[:120],
                                    "line": line.strip()[:180],
                                }
                            )
            except Exception as e:
                logger.warning(f"Error parsing access log {log_path}: {e}")

        # 2. Parse Error Logs for worker exits or crashes
        worker_crash_regex = re.compile(
            r'(?P<time>\d{4}/\d{2}/\d{2} \d{2}:\d{2}:\d{2})\s+\[alert\]\s+.*worker process \d+ (exited on signal|died)',
            re.IGNORECASE,
        )

        for log_path in found_error_logs:
            try:
                lines = cls._tail_file(log_path, max_lines)
                for line in lines:
                    m = worker_crash_regex.search(line)
                    if m:
                        raw_time = m.group("time")
                        anomalies["worker_crashes"] += 1
                        anomalies["total"] += 1
                        if len(anomalies["recent_events"]) < 20:
                            anomalies["recent_events"].append(
                                {
                                    "type": "Worker Crash",
                                    "timestamp": raw_time,
                                    "request": "Worker process exited abnormally",
                                    "line": line.strip()[:180],
                                }
                            )
            except Exception as e:
                logger.warning(f"Error parsing error log {log_path}: {e}")

        return anomalies

    @classmethod
    def get_complete_status(cls) -> Dict[str, Any]:
        """Aggregate comprehensive status for Nginx, sysctl, and security anomalies."""
        nginx_audit = cls.audit_nginx_configuration()
        sysctl_audit = cls.audit_sysctl()
        log_audit = cls.parse_nginx_logs(hours=24)

        overall_status = "SECURE" if (nginx_audit.get("hardened") and sysctl_audit.get("all_applied")) else "WARNING"

        return {
            "ok": True,
            "overall_status": overall_status,
            "nginx": nginx_audit,
            "sysctl": sysctl_audit,
            "anomalies_24h": log_audit,
            "timestamp": datetime.utcnow().strftime("%Y-%m-%dT%H:%M:%SZ"),
        }

    # --------------------------------------------------------------------------
    # Helper Methods
    # --------------------------------------------------------------------------
    @classmethod
    def _tail_file(cls, path: Path, num_lines: int) -> List[str]:
        """Read the last `num_lines` from a file efficiently."""
        try:
            with open(path, "r", encoding="utf-8", errors="ignore") as f:
                lines = f.readlines()
                return lines[-num_lines:] if len(lines) > num_lines else lines
        except Exception:
            return []

    @classmethod
    def _parse_nginx_timestamp(cls, raw: str) -> Optional[datetime]:
        """Parse Nginx log date e.g. '28/Oct/2026:14:00:00 +0000'."""
        try:
            # Strip timezone for simple comparison
            clean = raw.split()[0]
            return datetime.strptime(clean, "%d/%b/%Y:%H:%M:%S")
        except Exception:
            return None

    @classmethod
    def _get_dev_nginx_audit(cls, version: str) -> Dict[str, Any]:
        """Return realistic dev baseline audit for local Windows testing."""
        dirs = {}
        for k, v in cls.EXPECTED_DIRECTIVES.items():
            dirs[k] = {"current": v, "expected": v, "ok": True}
        return {
            "version": version,
            "installed": True,
            "hardened": True,
            "status": "SECURE",
            "hardening_file_exists": True,
            "config_test_ok": True,
            "directives": dirs,
            "missing_directives": [],
            "checked_at": datetime.utcnow().strftime("%Y-%m-%dT%H:%M:%SZ"),
        }

    @classmethod
    def _load_cached_status(cls) -> Dict[str, Any]:
        if STATUS_FILE_PATH.exists():
            try:
                return json.loads(STATUS_FILE_PATH.read_text(encoding="utf-8"))
            except Exception:
                pass
        return {}

    @classmethod
    def _save_cached_status(cls, updates: Dict[str, Any]) -> None:
        try:
            curr = cls._load_cached_status()
            curr.update(updates)
            STATUS_FILE_PATH.write_text(json.dumps(curr, indent=2, ensure_ascii=False), encoding="utf-8")
        except Exception as e:
            logger.warning(f"Could not save status cache: {e}")
